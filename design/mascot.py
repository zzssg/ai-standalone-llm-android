"""The mascot as a flat mark: a squirrel looking through a magnifying glass.

Fourth attempt at this animal, and the first that keeps the whole character.
Two earlier ones were derived from source art and failed on detail -- a painting
is too fine to survive 28dp, and tracing line art gives a hundred and thirty
paths of fur texture that read as fuzz. The third was designed rather than
derived, which fixed the detail problem and lost the animal: a head, a tail and
one enormous eye, which at any size reads as a cat with a monocle.

This one is designed from the new source art the way a poster is designed from a
photograph -- the pose, the proportions and the palette come from
design/squirrel_qwen.png, the shapes are built. What the picture supplies and the
earlier marks lacked is the pose: a whole squirrel, both eyes open, one of them
behind the glass and magnified by it. Two eyes is what separates a squirrel from
a cyclops, and the size difference between them is the joke.

The palette is measured from the picture rather than picked, by k-means over its
non-background pixels, and rounded to the values below. Flat means flat: no
gradients, no strokes, no shadows.

Everything is described as parameters and emitted, so a proportion changes by
editing a number, and the PIL preview renders the emitted geometry rather than
re-deriving it, so what is checked is what ships.

Everything the app ships is regenerated by one command, from the repository
root:

    R=app/src/main/res/drawable
    python design/mascot.py         --figure $R/ic_squirrel.xml         --head $R/ic_squirrel_head.xml         --launcher $R/ic_launcher_foreground.xml         --mono $R/ic_launcher_monochrome.xml         --notification $R/ic_notification.xml         --svg design/out/mascot.svg

and `--preview <file>` draws every variant at the sizes the app uses.
"""
import math
import sys

VIEWPORT = 100.0

# --- palette ---------------------------------------------------------------
#
# Eight clusters over the source picture; the six that carry area, rounded.
# Body and tail have to differ in value or the tail merges into the back --
# a painting separates them with an outline, and this mark has none.
FUR = "#EE7F44"        # body, head, ears, limbs
FUR_DEEP = "#CE6234"   # the tail, behind everything
FUR_DARK = "#A9421F"   # inside the ears
CREAM = "#F9E5C1"      # chest, muzzle, and the cheek seen through the lens
INK = "#3F211A"        # eyes and nose
BRASS = "#E0AE58"      # the rim and the cap of the handle
WOOD = "#B4764E"       # the handle
PAPER = "#FFFFFF"      # glints

# The handle is much lighter than the picture's walnut (#774331). It is the one
# part of the mark that leaves the animal's silhouette, so it is the one part
# drawn against the launcher ground rather than against fur -- and that ground
# is a dark brown, where walnut disappeared and left a paw holding a brass stud.
#
# Its value is a squeeze between three neighbours: too dark and it is lost on
# the ground, too light and it runs into the fur of the paw crossing it or the
# brass of its own cap. Note which way that pushes when the ground is lightened
# -- a mid brown handle and a dark brown ground converge, so lightening the
# ground alone makes the handle harder to see, not easier, and the handle has
# to move with it. Against the current #4E2A20 this holds 3.37, with 1.8 to the
# brass and 1.4 to the fur.


# --- primitives -------------------------------------------------------------

class Disc:
    def __init__(self, cx, cy, r, ry=None):
        self.cx, self.cy, self.rx, self.ry = cx, cy, r, ry if ry is not None else r


class Poly:
    def __init__(self, points):
        self.points = points


class Ring:
    def __init__(self, cx, cy, r_outer, r_inner):
        self.cx, self.cy, self.r_outer, self.r_inner = cx, cy, r_outer, r_inner


def polar(cx, cy, r, deg):
    a = math.radians(deg)
    return cx + r * math.cos(a), cy + r * math.sin(a)


def bezier(p0, p1, p2, p3, n):
    out = []
    for i in range(n + 1):
        t = i / n
        u = 1 - t
        out.append((u ** 3 * p0[0] + 3 * u * u * t * p1[0] + 3 * u * t * t * p2[0] + t ** 3 * p3[0],
                    u ** 3 * p0[1] + 3 * u * u * t * p1[1] + 3 * u * t * t * p2[1] + t ** 3 * p3[1]))
    return out


def oval(cx, cy, rx, ry, rot=0.0, n=28):
    """An ellipse at an angle, as a polygon.

    Android rotates groups, not paths, and a group per shape is a group per
    shape. Sampling the ellipse is cheaper than that and cheaper than a bezier
    approximation, and at these radii twenty-eight segments are sub-pixel.
    """
    a = math.radians(rot)
    ca, sa = math.cos(a), math.sin(a)
    pts = []
    for i in range(n):
        t = 2 * math.pi * i / n
        x, y = rx * math.cos(t), ry * math.sin(t)
        pts.append((cx + x * ca - y * sa, cy + x * sa + y * ca))
    return Poly(pts)


def ribbon(spine, w_root, w_tip, n=20):
    """A tapered stroke along a curve: the tail.

    A tail is a stroke that follows its own line and swells as it goes, so that
    is what this builds -- offset the spine by a half width that grows from root
    to tip, and round the tip off. Sampled coarsely on purpose: at the size this
    is drawn twenty segments are already sub-pixel, and forty push the path past
    the length the lint allows.
    """
    pts = bezier(*spine, n=n)
    left, right = [], []
    for i, (x, y) in enumerate(pts):
        t = i / (len(pts) - 1)
        # Swell early, then hold: a squirrel's tail is widest along its length,
        # not only at the very end.
        half = (w_root + (w_tip - w_root) * math.sin(t * math.pi / 2) ** 0.8) / 2
        j = min(i + 1, len(pts) - 1)
        k = max(i - 1, 0)
        dx, dy = pts[j][0] - pts[k][0], pts[j][1] - pts[k][1]
        length = math.hypot(dx, dy) or 1e-6
        nx, ny = -dy / length * half, dx / length * half
        left.append((x + nx, y + ny))
        right.append((x - nx, y - ny))

    tipx, tipy = pts[-1]
    ang = math.degrees(math.atan2(pts[-1][1] - pts[-2][1], pts[-1][0] - pts[-2][0]))
    cap = [polar(tipx, tipy, w_tip / 2, ang - 90 + 180 * i / 8) for i in range(9)]
    return Poly(left + cap + right[::-1])


def arcband(cx, cy, r, a0, a1, w, n=12):
    """A curved band along an arc: half of the mouth.

    A mouth built from straight capsules reads as a flat line whatever angle it
    is given. The reference smile is two shallow cups side by side, and a cup is
    an arc, so the arc is what gets drawn.
    """
    outer = [polar(cx, cy, r + w / 2, a0 + (a1 - a0) * i / n) for i in range(n + 1)]
    inner = [polar(cx, cy, r - w / 2, a0 + (a1 - a0) * i / n) for i in range(n + 1)]
    return Poly(outer + inner[::-1])


def capsule(x0, y0, x1, y1, r, n=8):
    ang = math.degrees(math.atan2(y1 - y0, x1 - x0))
    pts = [polar(x1, y1, r, ang - 90 + 180 * i / n) for i in range(n + 1)]
    pts += [polar(x0, y0, r, ang + 90 + 180 * i / n) for i in range(n + 1)]
    return Poly(pts)


def ear(tip, base_left, base_right, blunt=2.0):
    """A triangle with its apex chamfered off.

    Two earlier attempts at a soft tip went wrong the same way: a curve through
    the apex bows the sides inward and gives a flame, and an arc around the apex
    takes the reflex side and gives a knob on a stalk. Cutting the point off is
    both simpler and what actually reads as a rounded ear at icon size.
    """
    ax, ay = tip

    def pull(frm):
        dx, dy = frm[0] - ax, frm[1] - ay
        length = math.hypot(dx, dy) or 1e-6
        return (ax + dx / length * blunt, ay + dy / length * blunt)

    return Poly([base_left, pull(base_left), pull(base_right), base_right])


# --- the mark ---------------------------------------------------------------

#: What survives into the head crop.
#:
#: The whole figure at 28dp -- the avatar beside every assistant message -- is a
#: smudge with two ears, and the launcher's 48dp is not much kinder: the body
#: and the tail go first, and what is left of them is a lump behind the head.
#: Cropping to the head, its ears, the glass and the paw that holds it keeps
#: every part that survives, and it is still unmistakably this character.
HEAD_PARTS = ("ear", "head", "muzzle", "nose", "mouth", "eye", "glint",
              "handle", "cap", "paw", "toe", "lens", "rim", "big")

#: What survives into a single-colour icon.
#:
#: Flattened to one colour at 24dp a silhouette is a blob: the lens stops being
#: a hole and the eye stops being an eye. The glass with its pupil is the part
#: that still says what this is once colour is gone.
MONO_PARTS = ("rim", "handle", "cap", "bigeye")


def build(c):
    """Shapes in painting order."""
    out = []

    # The tail first, behind everything, in the deeper fur so it separates from
    # the back it passes behind.
    #
    # It is a plume on a stalk rather than one stroke. A tapered band along an
    # arc was tried first and through a dozen sets of numbers it always came out
    # the same: the inner edge of the band is hidden by the body, so the visible
    # silhouette is an arc of even width -- a shell, or the letter D. A tail
    # reads from its outline, and the outline wanted is a mass that swells clear
    # of the back and narrows to nothing where it meets the hip.
    out.append(("tailstalk", ribbon(c["tail_spine"], c["tail_root"], c["tail_tip"], n=12),
                FUR_DEEP))
    px_, py_, prx, pry, prot = c["plume"]
    out.append(("tailplume", oval(px_, py_, prx, pry, prot), FUR_DEEP))
    # A lighter core, inset: the picture's tail is banded, and one band is
    # enough to keep the plume from reading as a flat cut-out.
    out.append(("tailcore", oval(px_ + c["core_dx"], py_ + c["core_dy"],
                                 prx * c["core"], pry * c["core"], prot), FUR))

    # Ears before the head, so only their tips show above it.
    #
    # Their bases are seated on the head rather than laid across it. Written as
    # a flat edge at one height, the base is a chord of a straight line against
    # a circle, and the outer corner of each ear lands outside it: the ear then
    # ends in a horizontal cut hanging over the background with a wedge of gap
    # between it and the skull. Pulling both corners onto a circle a little
    # inside the head's own makes the join impossible to miss instead of a
    # number that has to be kept in agreement with head_r, ear_dx and ear_w.
    for side in (-1, 1):
        cx = c["head_cx"] + side * c["ear_dx"]
        tip = (cx + side * c["ear_tilt"], c["head_cy"] - c["ear_h"])

        def seat(x, y):
            ang = math.degrees(math.atan2(y - c["head_cy"], x - c["head_cx"]))
            return polar(c["head_cx"], c["head_cy"], c["head_r"] - c["ear_sink"], ang)

        base_l = seat(cx - c["ear_w"] / 2, c["head_cy"] - c["ear_base"])
        base_r = seat(cx + c["ear_w"] / 2, c["head_cy"] - c["ear_base"])
        out.append((f"ear{side}", ear(tip, base_l, base_r), FUR))
        # The dark inside, a smaller triangle on the same axis.
        k = c["ear_inner"]
        mid = ((base_l[0] + base_r[0]) / 2, (base_l[1] + base_r[1]) / 2)

        def lerp(p, t=k):
            return (mid[0] + (p[0] - mid[0]) * t, mid[1] + (p[1] - mid[1]) * t)

        out.append((f"earin{side}", ear(lerp(tip), lerp(base_l), lerp(base_r), 1.4), FUR_DARK))

    out.append(("body", Disc(c["body_cx"], c["body_cy"], c["body_rx"], c["body_ry"]), FUR))

    # The arm that reaches up to the glass, under both the chest and the head:
    # it ends where the cream begins and where the cheek begins, so neither gets
    # a wedge bitten out of it. Painted over the chest it cut a notch in the
    # oval that read as damage rather than as a limb.
    out.append(("arm", capsule(*c["arm"], c["arm_w"] / 2), FUR))

    out.append(("chest", Disc(c["chest_cx"], c["chest_cy"], c["chest_rx"], c["chest_ry"]), CREAM))

    out.append(("head", Disc(c["head_cx"], c["head_cy"], c["head_r"]), FUR))
    out.append(("muzzle", Disc(c["muzzle_cx"], c["muzzle_cy"],
                               c["muzzle_rx"], c["muzzle_ry"]), CREAM))
    out.append(("nose", Disc(c["nose_cx"], c["nose_cy"], c["nose_r"] * 1.2, c["nose_r"]), INK))

    # The mouth: two cups meeting under the nose. It is half a pixel wide at
    # 28dp and reads there as a soft shadow, which is the right amount of mouth
    # for an avatar; at hero size it is the difference between a character and
    # a diagram.
    mr, my = c["mouth_r"], c["nose_cy"] + c["mouth_dy"]
    for side in (-1, 1):
        out.append((f"mouth{side}", arcband(c["nose_cx"] + side * mr, my, mr,
                                            0, 180, c["mouth_w"]), INK))

    # The open eye, at the size an eye actually is. It is here to be compared
    # with the other one.
    ex, ey, er = c["eye_cx"], c["eye_cy"], c["eye_r"]
    out.append(("eye", Disc(ex, ey, er), INK))
    out.append(("glint", Disc(ex + er * 0.36, ey - er * 0.38, er * 0.34), PAPER))

    # The magnifier. Handle first so the paw closes over it.
    gx, gy, gr = c["glass_cx"], c["glass_cy"], c["glass_r"]
    hx, hy = polar(gx, gy, gr + c["rim_w"] / 2, c["handle_deg"])
    tx, ty = polar(gx, gy, gr + c["rim_w"] / 2 + c["handle_len"], c["handle_deg"])
    out.append(("handle", capsule(hx, hy, tx, ty, c["handle_w"] / 2), WOOD))
    out.append(("cap", Disc(tx, ty, c["handle_w"] * 0.62), BRASS))

    # The lens is filled with the cheek it sits over, not with glass: what the
    # picture shows through it is fur, and a white disc on an orange head is a
    # hole punched in the animal.
    out.append(("lens", Disc(gx, gy, gr), CREAM))
    out.append(("rim", Ring(gx, gy, gr + c["rim_w"], gr), BRASS))

    # The paw last of the three, closing over the handle in front of the rim.
    # Behind it, the hand looked like a lump growing out of the glass.
    px, py = polar(gx, gy, gr + c["rim_w"] / 2 + c["paw_at"], c["handle_deg"])
    out.append(("paw", oval(px, py, c["paw_rx"], c["paw_ry"], c["handle_deg"] + 90), FUR))
    # Toes, as bumps on the edge that faces the glass. A bare oval on a stick
    # is a blob; three notches in its outline are what make it a hand, and they
    # cost nothing at small sizes because they melt back into the oval.
    ux, uy = polar(0, 0, 1, c["handle_deg"])
    for i in (-1, 0, 1):
        out.append((f"toe{i}", Disc(px - ux * c["toe_out"] - uy * i * c["toe_gap"],
                                    py - uy * c["toe_out"] + ux * i * c["toe_gap"],
                                    c["toe_r"]), FUR))

    # And the eye behind it, magnified. That oversize is the whole joke, so it
    # must not be trimmed back to something anatomical.
    bx, by, br = gx + c["big_dx"], gy + c["big_dy"], c["big_r"]
    out.append(("bigeye", Disc(bx, by, br), INK))
    out.append(("bigglint", Disc(bx + br * 0.36, by - br * 0.38, br * 0.32), PAPER))
    return out


