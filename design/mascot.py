# --- emit -------------------------------------------------------------------

def _n(v):
    return f"{v:.1f}"


def path_data(prim):
    if isinstance(prim, Disc):
        return (f"M{_n(prim.cx - prim.rx)},{_n(prim.cy)}"
                f"a{_n(prim.rx)},{_n(prim.ry)} 0 1,0 {_n(2 * prim.rx)},0"
                f"a{_n(prim.rx)},{_n(prim.ry)} 0 1,0 {_n(-2 * prim.rx)},0Z")
    if isinstance(prim, Ring):
        ro, ri = prim.r_outer, prim.r_inner
        return (f"M{_n(prim.cx - ro)},{_n(prim.cy)}"
                f"a{_n(ro)},{_n(ro)} 0 1,0 {_n(2 * ro)},0"
                f"a{_n(ro)},{_n(ro)} 0 1,0 {_n(-2 * ro)},0Z"
                f"M{_n(prim.cx - ri)},{_n(prim.cy)}"
                f"a{_n(ri)},{_n(ri)} 0 1,1 {_n(2 * ri)},0"
                f"a{_n(ri)},{_n(ri)} 0 1,1 {_n(-2 * ri)},0Z")
    head = prim.points[0]
    return (f"M{_n(head[0])},{_n(head[1])}"
            + "".join(f"L{_n(x)},{_n(y)}" for x, y in prim.points[1:]) + "Z")


def _select(shapes, parts):
    return [s for s in shapes if s[0].startswith(parts)]


def variant(cfg, crop=None, monochrome=False):
    shapes = build(cfg)
    if crop:
        shapes = _select(shapes, crop)
    if monochrome:
        shapes = [(n, p, PAPER) for n, p, c in _select(shapes, MONO_PARTS)]
    return shapes


def to_vector_drawable(cfg, size=108, crop=None, monochrome=False, fit=0.94, note=""):
    shapes = variant(cfg, crop=crop, monochrome=monochrome)
    body = []
    for name, prim, colour in shapes:
        fill = ' android:fillType="evenOdd"' if isinstance(prim, Ring) else ""
        body.append(f"        <!-- {name} -->\n"
                    f"        <path\n"
                    f'            android:fillColor="#FF{colour[1:]}"{fill}\n'
                    f'            android:pathData="{path_data(prim)}" />')

    (x0, x1), (y0, y1) = _bounds(shapes)
    scale = VIEWPORT * fit / max(x1 - x0, y1 - y0)
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2

    group = (f'    <group\n'
             f'        android:pivotX="{_n(cx)}"\n'
             f'        android:pivotY="{_n(cy)}"\n'
             f'        android:scaleX="{_n(scale)}"\n'
             f'        android:scaleY="{_n(scale)}"\n'
             f'        android:translateX="{_n(VIEWPORT / 2 - cx)}"\n'
             f'        android:translateY="{_n(VIEWPORT / 2 - cy)}">\n\n')

    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            "<!--\n"
            f"    Generated by design/mascot.py. {note}\n"
            "    Flat shapes, no gradients and no strokes. Regenerate rather\n"
            "    than editing by hand.\n"
            "-->\n"
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{size}dp"\n'
            f'    android:height="{size}dp"\n'
            f'    android:viewportWidth="{VIEWPORT:.0f}"\n'
            f'    android:viewportHeight="{VIEWPORT:.0f}">\n\n'
            + group + "\n\n".join(body) + "\n    </group>\n</vector>\n")


def to_svg(cfg, crop=None):
    shapes = variant(cfg, crop=crop)
    body = "\n".join(
        f'  <path fill="{colour}" fill-rule="evenodd" d="{path_data(prim)}"/>'
        for _, prim, colour in shapes)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {VIEWPORT:.0f} '
            f'{VIEWPORT:.0f}" width="{VIEWPORT:.0f}" height="{VIEWPORT:.0f}">\n'
            f"{body}\n</svg>\n")


def _bounds(shapes):
    xs, ys = [], []
    for _, prim, _ in shapes:
        if isinstance(prim, Disc):
            xs += [prim.cx - prim.rx, prim.cx + prim.rx]
            ys += [prim.cy - prim.ry, prim.cy + prim.ry]
        elif isinstance(prim, Ring):
            xs += [prim.cx - prim.r_outer, prim.cx + prim.r_outer]
            ys += [prim.cy - prim.r_outer, prim.cy + prim.r_outer]
        else:
            xs += [p[0] for p in prim.points]
            ys += [p[1] for p in prim.points]
    return (min(xs), max(xs)), (min(ys), max(ys))


def _render(shapes, px, paper):
    from PIL import Image, ImageDraw
    scale = px / VIEWPORT
    img = Image.new("RGBA", (px, px), paper)
    for _, prim, colour in shapes:
        rgb = tuple(int(colour[i:i + 2], 16) for i in (1, 3, 5)) + (255,)
        layer = Image.new("RGBA", (px, px), (0, 0, 0, 0))
        draw = ImageDraw.Draw(layer)
        if isinstance(prim, Disc):
            draw.ellipse([(prim.cx - prim.rx) * scale, (prim.cy - prim.ry) * scale,
                          (prim.cx + prim.rx) * scale, (prim.cy + prim.ry) * scale], fill=rgb)
        elif isinstance(prim, Ring):
            draw.ellipse([(prim.cx - prim.r_outer) * scale, (prim.cy - prim.r_outer) * scale,
                          (prim.cx + prim.r_outer) * scale, (prim.cy + prim.r_outer) * scale],
                         fill=rgb)
            draw.ellipse([(prim.cx - prim.r_inner) * scale, (prim.cy - prim.r_inner) * scale,
                          (prim.cx + prim.r_inner) * scale, (prim.cy + prim.r_inner) * scale],
                         fill=(0, 0, 0, 0))
        else:
            draw.polygon([(x * scale, y * scale) for x, y in prim.points], fill=rgb)
        img.alpha_composite(layer)
    return img


def _fitted(cfg, crop=None, monochrome=False, fit=0.94):
    """The shapes as the drawable places them: scaled and centred in the box."""
    shapes = variant(cfg, crop=crop, monochrome=monochrome)
    (x0, x1), (y0, y1) = _bounds(shapes)
    scale = VIEWPORT * fit / max(x1 - x0, y1 - y0)
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2

    def place(x, y):
        return (VIEWPORT / 2 + (x - cx) * scale, VIEWPORT / 2 + (y - cy) * scale)

    out = []
    for name, prim, colour in shapes:
        if isinstance(prim, Disc):
            px, py = place(prim.cx, prim.cy)
            prim = Disc(px, py, prim.rx * scale, prim.ry * scale)
        elif isinstance(prim, Ring):
            px, py = place(prim.cx, prim.cy)
            prim = Ring(px, py, prim.r_outer * scale, prim.r_inner * scale)
        else:
            prim = Poly([place(x, y) for x, y in prim.points])
        out.append((name, prim, colour))
    return out


def preview(cfg, path, px=560, paper=(250, 246, 242, 255)):
    """Every variant at full size, and each at the sizes the app draws it."""
    from PIL import Image
    sheets = [
        ("figure", _fitted(cfg), (96, 48, 28)),
        ("head", _fitted(cfg, crop=HEAD_PARTS), (48, 28, 20)),
        ("launcher", _fitted(cfg, crop=HEAD_PARTS, fit=0.56), (48, 28)),
        ("mono", _fitted(cfg, crop=HEAD_PARTS, monochrome=True, fit=0.56), (24,)),
    ]
    strip = px // 3
    sheet = Image.new("RGBA", ((px + strip) * len(sheets), px), paper)
    for col, (name, shapes, sizes) in enumerate(sheets):
        ground = (60, 48, 40, 255) if name == "mono" else paper
        big = _render(shapes, px, ground)
        x0 = col * (px + strip)
        sheet.alpha_composite(big, (x0, 0))
        y = 0
        for dp in sizes:
            shot = big.resize((dp * 3, dp * 3), Image.LANCZOS)
            sheet.alpha_composite(shot, (x0 + px + (strip - dp * 3) // 2, y + 12))
            y += dp * 3 + 24
    sheet.convert("RGB").save(path)
    return path


VARIANTS = {
    "--figure": dict(note="The whole character, for the hero screens.",
                     kwargs={}),
    "--head": dict(note="The head crop, for the 28dp avatar beside a message.",
                   kwargs={"crop": HEAD_PARTS}),
    # 0.56, not the 0.66 the safe zone allows a square: the guarantee is a
    # circle of 66 of the 108, and the mark's extremes are an ear tip at the top
    # and the cap of the handle at the bottom left -- corners of its box. Fitted
    # to 0.66 a round mask takes the tip off, which reads as a mistake rather
    # than as a crop.
    "--launcher": dict(note="The head crop, fitted inside the launcher safe circle.",
                       kwargs={"crop": HEAD_PARTS, "fit": 0.56}),
    "--mono": dict(note="One colour, for the themed launcher icon.",
                   kwargs={"crop": HEAD_PARTS, "monochrome": True, "fit": 0.56}),
    "--notification": dict(note="One colour at 24dp, for the status bar.",
                           kwargs={"crop": HEAD_PARTS, "monochrome": True, "fit": 0.94}),
}


